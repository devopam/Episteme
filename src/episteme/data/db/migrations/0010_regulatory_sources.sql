-- Migration 0010 -- regulatory sources: reference-feed records, the substance
-- dictionary and its xref, FAERS typed tables and signal tables, label sections,
-- and LIST partitions for the dailymed and ema_epar text sources.
-- Idempotent. Apply as episteme_sys_admin (owner). One transaction (see 0005).
-- Design: docs/superpowers/specs/2026-11-02-regulatory-sources-design.md, 5.2 to 5.5.
--
-- PRECONDITION: the default partitions hold no dailymed or ema_epar row. CREATE
-- TABLE ... PARTITION OF scans the DEFAULT partition and fails if any row matches
-- the new bound (see 0009). The scan runs under an ACCESS EXCLUSIVE lock on
-- articles / article_body: apply with no load running.
--
-- Signal tables: the column is named substance_key in every table, as in the
-- spec, but the first key columns of the signal tables hold MOIETY keys
-- (substance.moiety_key). A signal counts the active moiety, so metformin
-- hydrochloride and metformin are one row. The exact substance stays in
-- substance_xref and faers_entry_substance.
--
-- Keys are never reused or renumbered (spec 5.3). No table here stores a foreign
-- key to substance: an improved mapping changes xref rows only.
--
-- quarter columns hold the first day of the calendar quarter (a date), from
-- faers_report.receive_date, the first receipt.
--
-- reg_record: LIST (dataset), then LIST (release_id). The migration creates no
-- dataset or release partition. A loader creates the partition of a release, loads,
-- builds its indexes and then switches reg_release.is_latest. Queries name
-- dataset and release_id as literals, so that the plan prunes to one leaf.
--
-- FAERS parents (faers_report, faers_drug, faers_reaction): RANGE (receive_year),
-- one partition per year 2004 to 2030, and a default for a report with no usable
-- date. The parents hold NO index. The FAERS loader builds the indexes per
-- generation, after the load.
--
-- Grants: DML through the parent checks the parent's privileges only, and
-- schema.sql's ALTER DEFAULT PRIVILEGES covers the new tables as well.

BEGIN;

-- ---------------------------------------------------------------------------
-- 5.2 reg_release (registry) and reg_record (all reference feeds)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS episteme.reg_release (
    dataset     text        NOT NULL,
    release_id  text        NOT NULL,
    loaded_at   timestamptz NOT NULL DEFAULT now(),
    rows        bigint      NOT NULL DEFAULT 0,
    status      text        NOT NULL,
    is_latest   boolean     NOT NULL DEFAULT false,
    PRIMARY KEY (dataset, release_id)
);
-- Exactly one latest release per dataset.
CREATE UNIQUE INDEX IF NOT EXISTS reg_release_one_latest_idx
    ON episteme.reg_release (dataset) WHERE is_latest;

CREATE TABLE IF NOT EXISTS episteme.reg_record (
    dataset         text   NOT NULL,
    release_id      text   NOT NULL,
    record_key      text   NOT NULL,
    jurisdiction    text,
    substance_names text[],
    product_keys    text[],
    event_date      date,
    payload         jsonb  NOT NULL,
    source_file     text   NOT NULL
) PARTITION BY LIST (dataset);

-- ---------------------------------------------------------------------------
-- 5.3 substance and substance_xref
-- ---------------------------------------------------------------------------
-- One row per UNII. A substance with no UNII (some EU-only names) still gets a
-- key, with no moiety_key. moiety_key points at the active moiety, or at the
-- substance itself.
CREATE TABLE IF NOT EXISTS episteme.substance (
    substance_key  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unii           text,
    preferred_name text,
    moiety_key     bigint
);
CREATE UNIQUE INDEX IF NOT EXISTS substance_unii_idx
    ON episteme.substance (unii) WHERE unii IS NOT NULL;
CREATE INDEX IF NOT EXISTS substance_moiety_key_idx ON episteme.substance (moiety_key);

CREATE TABLE IF NOT EXISTS episteme.substance_xref (
    substance_key bigint NOT NULL,
    id_type       text   NOT NULL,
    id_value      text   NOT NULL,
    method        text   NOT NULL,
    confidence    real,
    source        text   NOT NULL,
    PRIMARY KEY (id_type, id_value, substance_key)
);
CREATE INDEX IF NOT EXISTS substance_xref_substance_key_idx
    ON episteme.substance_xref (substance_key);

-- ---------------------------------------------------------------------------
-- 5.4 FAERS typed tables
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS episteme.faers_report (
    safetyreportid            text NOT NULL,
    receive_year              integer,
    receive_date              date,  -- the first receipt: the earlier of the two below
    receipt_date              date,  -- receiptdate as published
    source_receive_date       date,  -- receivedate as published
    version                   integer,
    serious                   boolean,
    serious_death             boolean,
    serious_hospitalization   boolean,
    serious_life_threatening  boolean,
    serious_disabling         boolean,
    serious_congenital        boolean,
    serious_other             boolean,
    country                   text,
    sex                       text,
    age_years                 real,
    weight_kg                 real,
    source_file               text
) PARTITION BY RANGE (receive_year);

-- For a database that applied an earlier draft of this file.
ALTER TABLE episteme.faers_report ADD COLUMN IF NOT EXISTS source_receive_date date;

CREATE TABLE IF NOT EXISTS episteme.faers_drug (
    safetyreportid text NOT NULL,
    seq            integer NOT NULL,
    receive_year   integer,
    role           text,
    drug_entry_id  bigint,
    batch_number   text,
    batch_norm     text,
    route          text,
    indication     text,
    source_file    text
) PARTITION BY RANGE (receive_year);

CREATE TABLE IF NOT EXISTS episteme.faers_reaction (
    safetyreportid text NOT NULL,
    seq            integer NOT NULL,
    receive_year   integer,
    term_id        bigint,
    outcome        text,
    source_file    text
) PARTITION BY RANGE (receive_year);

DO $$
DECLARE
    parent text;
    y      integer;
BEGIN
    FOREACH parent IN ARRAY ARRAY['faers_report', 'faers_drug', 'faers_reaction'] LOOP
        FOR y IN 2004..2030 LOOP
            EXECUTE format(
                'CREATE TABLE IF NOT EXISTS episteme.%I PARTITION OF episteme.%I '
                'FOR VALUES FROM (%s) TO (%s)',
                parent || '_y' || y, parent, y, y + 1);
        END LOOP;
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS episteme.%I PARTITION OF episteme.%I DEFAULT',
            parent || '_default', parent);
    END LOOP;
END
$$;

-- Dictionary of distinct (product name, active substance, annotation) combinations.
-- The unique index is on an md5 of the three values (NULL as empty), not on the
-- text: a long annotation would overflow a btree entry. Load with
-- ON CONFLICT ((md5(...)))  using exactly the expression below.
CREATE TABLE IF NOT EXISTS episteme.faers_drug_entry (
    drug_entry_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name     text,
    active_substance text,
    annotation       text
);
CREATE UNIQUE INDEX IF NOT EXISTS faers_drug_entry_uq
    ON episteme.faers_drug_entry (
        (md5(coalesce(product_name, '') || chr(31) || coalesce(active_substance, '')
             || chr(31) || coalesce(annotation, '')))
    );

-- The bridge from an entry to substance_xref. Improving a link updates this
-- small table only.
CREATE TABLE IF NOT EXISTS episteme.faers_entry_substance (
    drug_entry_id bigint NOT NULL,
    substance_key bigint NOT NULL,
    method        text   NOT NULL,
    PRIMARY KEY (drug_entry_id, substance_key)
);
CREATE INDEX IF NOT EXISTS faers_entry_substance_substance_key_idx
    ON episteme.faers_entry_substance (substance_key);

-- Reaction term as published (a MedDRA preferred term in FDA's public data).
CREATE TABLE IF NOT EXISTS episteme.faers_term (
    term_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term    text   NOT NULL UNIQUE
);

-- Signal tables: rebuilt per generation and swapped with it. substance_key holds
-- a moiety key (see the header).
CREATE TABLE IF NOT EXISTS episteme.faers_pair_quarter (
    substance_key_a bigint  NOT NULL,
    substance_key_b bigint  NOT NULL,
    quarter         date    NOT NULL,
    reports_suspect integer NOT NULL,
    reports_any     integer NOT NULL,
    PRIMARY KEY (substance_key_a, quarter, substance_key_b)
);

CREATE TABLE IF NOT EXISTS episteme.faers_event_quarter (
    substance_key   bigint  NOT NULL,
    term_id         bigint  NOT NULL,
    quarter         date    NOT NULL,
    reports_suspect integer NOT NULL,
    reports_any     integer NOT NULL,
    PRIMARY KEY (substance_key, term_id, quarter)
);

-- Denominators of the statistic. reports_over_pair_cap counts the reports left
-- out of the pair counts because they list more drugs than the configured cap.
CREATE TABLE IF NOT EXISTS episteme.faers_quarter_totals (
    quarter               date    PRIMARY KEY,
    reports               integer NOT NULL,
    reports_over_pair_cap integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS episteme.faers_batch_coverage (
    substance_key bigint  NOT NULL,
    quarter       date    NOT NULL,
    drug_rows     integer NOT NULL,
    with_batch    integer NOT NULL,
    PRIMARY KEY (substance_key, quarter)
);

CREATE TABLE IF NOT EXISTS episteme.faers_batch_quarter (
    substance_key bigint  NOT NULL,
    batch_norm    text    NOT NULL,
    quarter       date    NOT NULL,
    reports       integer NOT NULL,
    PRIMARY KEY (substance_key, batch_norm, quarter)
);

-- Lots extracted from the free-text code_info of drug/enforcement. lot_norm is
-- NULL for a recall with no extractable lot (counted as a gap).
CREATE TABLE IF NOT EXISTS episteme.recall_lot (
    recall_number   text NOT NULL,
    release_id      text NOT NULL,
    substance_names text[],
    lot_raw         text,
    lot_norm        text,
    method          text
);
CREATE INDEX IF NOT EXISTS recall_lot_lot_norm_idx ON episteme.recall_lot (lot_norm);
CREATE INDEX IF NOT EXISTS recall_lot_recall_idx ON episteme.recall_lot (release_id, recall_number);

-- ---------------------------------------------------------------------------
-- 5.5 Text: labels and EPAR documents
-- ---------------------------------------------------------------------------
-- One LIST partition each, no year ladder (as 0009): labels and EPARs have no
-- meaningful publication year for partitioning.
CREATE TABLE IF NOT EXISTS episteme.articles_dailymed
    PARTITION OF episteme.articles FOR VALUES IN ('dailymed');
CREATE TABLE IF NOT EXISTS episteme.articles_ema_epar
    PARTITION OF episteme.articles FOR VALUES IN ('ema_epar');
CREATE TABLE IF NOT EXISTS episteme.article_body_dailymed
    PARTITION OF episteme.article_body FOR VALUES IN ('dailymed');
CREATE TABLE IF NOT EXISTS episteme.article_body_ema_epar
    PARTITION OF episteme.article_body FOR VALUES IN ('ema_epar');

-- Labelled sections point into the body text by offset: no copy of the text.
CREATE TABLE IF NOT EXISTS episteme.label_section (
    article_id   text    NOT NULL,
    loinc_code   text    NOT NULL,
    title        text,
    start_offset integer NOT NULL,
    end_offset   integer NOT NULL
);
CREATE INDEX IF NOT EXISTS label_section_article_loinc_idx
    ON episteme.label_section (article_id, loinc_code);

CREATE TABLE IF NOT EXISTS episteme.label_substance (
    article_id    text   NOT NULL,
    substance_key bigint,
    unii          text,
    ndc_product   text
);
CREATE INDEX IF NOT EXISTS label_substance_substance_key_idx
    ON episteme.label_substance (substance_key);
CREATE INDEX IF NOT EXISTS label_substance_article_idx ON episteme.label_substance (article_id);

COMMIT;
